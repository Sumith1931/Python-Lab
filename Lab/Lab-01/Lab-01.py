def sequence():
    nums = [100, 4, 200, 1, 3, 2]
    nums.sort()

    seq = []
    longest = []

    for i in range(len(nums)):
        if i == 0 or nums[i] == nums[i - 1] + 1:
            seq.append(nums[i])
        else:
            if len(seq) > len(longest):
                longest = seq
            seq = [nums[i]]

    if len(seq) > len(longest):
        longest = seq

    print(longest)
    print(len(longest))

sequence()