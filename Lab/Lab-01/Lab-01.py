def count_vowels(s):
    vowels = "aeiou"
    result = {}

    for v in vowels:
        count = 0

        for ch in s:
            if ch == v:
                count = count + 1

        result[v] = count

    return result


s = input("Enter a string: ")
print(count_vowels(s))

