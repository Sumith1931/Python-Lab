def maxProfit():
    prices = [7, 1, 5, 3, 6, 4, 5]
    days = [1, 2, 3, 4, 5, 6, 7]

    max_profit = 0
    n = len(prices)
    for i in range(n):
        for j in range(i + 1, n):
            if prices[j] - prices[i] > max_profit:
                max_profit = prices[j] - prices[i]
                buy_day = days[i]
                sell_day = days[j]

    print("Buy on day:", buy_day)
    print("Sell on day:", sell_day)
    print("Maximum profit:", max_profit)

maxProfit()

